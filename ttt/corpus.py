_SPACE = re.compile(r"\s+")
_WORD = re.compile(r"\w+")
# 超长空白串多半来自损坏的 HTML 抽取，截到 128 个字符。
MAX_WHITESPACE_RUN = 128
_LONG_SPACE = re.compile(r"\s{%d,}" % (MAX_WHITESPACE_RUN + 1))

LONG_NGRAM = 13
SHORT_NGRAM = 8
# 至少这么多个词含字母，纯数字序列（表格、测试用例里的数组）不参与匹配。
LONG_MIN_ALPHA = 8
SHORT_MIN_ALPHA = 6
# held-out 长文档按连续逐字重合的词数判定；50 个词长于任何一条署名行或单句引文。
SPAN_WORDS = 50
SPAN_RUN = SPAN_WORDS - LONG_NGRAM + 1
# 只有这些字段里不足 13 个词的短题干才用 8-gram 兜底，避免选项里的通用短语误伤训练文档。
PRIMARY_KEYS = frozenset({"question", "goal", "ctx", "sentence", "question_stem", "input", "prompt", "problem"})

