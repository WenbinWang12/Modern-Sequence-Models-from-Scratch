"""多领域预训练语料：文本清洗、全文去重摘要、评测去污染和来源渲染。

去污染沿用公开大规模预训练管线的通行做法：把评测文本切成词级 13-gram 并哈希成索引。
词按 ``\\w+`` 切分并转小写，所以标点、换行和 Markdown 记号的差别不影响匹配。判定分两类：

- benchmark 题目：训练文档只要与任何题目共享一个 13-gram 就整篇剔除；题干不足 13 个词时
  退到 8-gram；
- held-out 长文档（书籍）：训练文档与某篇 held-out 文档有连续 ``SPAN_WORDS`` 个词逐字重合
  才剔除。书籍里有大量与内容无关的公共文字（电子书制作署名、版权声明、常见引文），
  单个 13-gram 命中不能说明训练文档抄了 held-out 文档。
"""

