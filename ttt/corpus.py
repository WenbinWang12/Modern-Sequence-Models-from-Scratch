def clean_text(text: str) -> str:
    """去掉空字符、截短超长空白串并去掉首尾空白，其余内容原样保留。"""
    try:
        text.encode("utf-8")
    except UnicodeEncodeError:
        # JSON 里偶尔有落单的代理字符，无法编码成 UTF-8，替换成问号。
        text = text.encode("utf-8", "replace").decode("utf-8")
    text = text.replace("\x00", "")
    return _LONG_SPACE.sub(lambda match: match.group(0)[:MAX_WHITESPACE_RUN], text).strip()


def document_digest(text: str) -> bytes:
    """规范化全文摘要：小写、连续空白压成一个空格。"""
    normalised = _SPACE.sub(" ", text.lower()).strip()
    return hashlib.blake2b(normalised.encode("utf-8"), digest_size=12).digest()


def sampled(key: bytes, rate: float) -> bool:
    """按 key 的校验和做确定性抽样，同一个 key 的结果不随进程和运行变化。"""
    return rate >= 1.0 or zlib.crc32(key) < rate * 4294967296.0


@functools.lru_cache(maxsize=None)
def _multipliers(length: int) -> np.ndarray:
    """位置相关的奇数乘子（splitmix64），让 n-gram 哈希对词序敏感。"""
    mask, state, values = (1 << 64) - 1, 0, []
    for _ in range(length):
        state = (state + 0x9E3779B97F4A7C15) & mask
        mixed = ((state ^ (state >> 30)) * 0xBF58476D1CE4E5B9) & mask
        mixed = ((mixed ^ (mixed >> 27)) * 0x94D049BB133111EB) & mask
        values.append((mixed ^ (mixed >> 31)) | 1)
    return np.asarray(values, dtype=np.uint64)


class _WordHasher:
    """把文本切成词并映射到 64 位哈希；最低位记录这个词是否含字母。"""

    def __init__(self, limit: int = 2_000_000):
        self._cache: dict[str, int] = {}
        self._limit = limit

    def _hash(self, word: str) -> int:
        value = int.from_bytes(hashlib.blake2b(word.encode("utf-8"), digest_size=8).digest(), "little")
        value = (value & ~1) | int(any(character.isalpha() for character in word))
        if len(self._cache) < self._limit:
            self._cache[word] = value
        return value

    def __call__(self, text: str) -> np.ndarray:
        cache, compute = self._cache, self._hash
        values = [cache.get(word) or compute(word) for word in _WORD.findall(text.lower())]
        return np.asarray(values, dtype=np.uint64)


def window_hashes(words: np.ndarray, length: int, min_alpha: int) -> tuple[np.ndarray, np.ndarray]:
    """所有长度为 ``length`` 的词窗口的哈希，以及每个窗口里含字母的词是否不少于 ``min_alpha``。"""
    count = words.size - length + 1
    if count <= 0:
        return np.zeros(0, dtype=np.uint64), np.zeros(0, dtype=bool)
    hashes = np.zeros(count, dtype=np.uint64)
    for offset, multiplier in enumerate(_multipliers(length)):
        hashes += words[offset : offset + count] * multiplier
    alpha = np.concatenate(([0], np.cumsum(words & np.uint64(1), dtype=np.int64)))
    return hashes, (alpha[length:] - alpha[:-length]) >= min_alpha


def ngram_hashes(words: np.ndarray, length: int, min_alpha: int) -> np.ndarray:
    """``window_hashes`` 中含字母的词足够多的那些窗口。"""
    hashes, enough = window_hashes(words, length, min_alpha)
    return hashes[enough]


def _lookup(table: np.ndarray, queries: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    positions = np.minimum(np.searchsorted(table, queries), table.size - 1)
    return positions, np.asarray(table[positions]) == queries


def _first_hit(table: np.ndarray, queries: np.ndarray) -> int:
    if not table.size or not queries.size:
        return -1
    positions, hit = _lookup(table, queries)
    hits = np.flatnonzero(hit)
    return int(positions[hits[0]]) if hits.size else -1


def _longest_run(table: np.ndarray, queries: np.ndarray, enough: np.ndarray, minimum: int) -> int:
    """最长的一段连续命中不短于 ``minimum`` 时返回它起点在表中的位置，否则返回 -1。"""
    if not table.size or queries.size < minimum:
        return -1
    positions, hit = _lookup(table, queries)
    hit &= enough
    if int(hit.sum()) < minimum:
        return -1
    padded = np.concatenate(([False], hit, [False]))
    edges = np.flatnonzero(padded[1:] != padded[:-1])
    begins, lengths = edges[::2], edges[1::2] - edges[::2]
    longest = int(lengths.argmax())
    return int(positions[begins[longest]]) if lengths[longest] >= minimum else -1


class EvalIndex:
    """评测文本的 n-gram 索引。``match`` 返回 ``(层级, 评测来源)``，未命中返回 ``None``。

    三张表：``ngram13`` 和 ``ngram8`` 来自 benchmark 题目，命中一个就算；``span13`` 来自
    held-out 长文档，需要连续命中 ``SPAN_RUN`` 个 13-gram（即 ``SPAN_WORDS`` 个词逐字重合）。
    """

    tables = ("ngram13", "ngram8", "span13")
    span_tier = f"span{SPAN_WORDS}"

    def __init__(self, owners, *arrays):
        self.owners = list(owners)
        self._arrays = dict(zip((f"{name}{part}" for name in self.tables for part in ("", "_owner")), arrays))
        self._hasher = _WordHasher()

    @property
    def sizes(self) -> dict[str, int]:
        return {name: int(self._arrays[name].size) for name in self.tables}

    def _owner(self, table: str, position: int) -> str:
        return self.owners[int(self._arrays[f"{table}_owner"][position])]

    def match(self, text: str):
        words = self._hasher(text)
        long_hashes, long_enough = window_hashes(words, LONG_NGRAM, LONG_MIN_ALPHA)
        position = _first_hit(self._arrays["ngram13"], long_hashes[long_enough])
        if position >= 0:
            return "ngram13", self._owner("ngram13", position)
        position = _first_hit(self._arrays["ngram8"], ngram_hashes(words, SHORT_NGRAM, SHORT_MIN_ALPHA))
        if position >= 0:
            return "ngram8", self._owner("ngram8", position)
        position = _longest_run(self._arrays["span13"], long_hashes, long_enough, SPAN_RUN)
        if position >= 0:
            return self.span_tier, self._owner("span13", position)
        return None

    def save(self, directory, **metadata) -> None:
        directory = Path(directory)
        directory.mkdir(parents=True, exist_ok=True)
        for name, array in self._arrays.items():
            np.save(directory / f"{name}.npy", np.asarray(array), allow_pickle=False)
        summary = {
            "format": "ttt_eval_index_v2",
            "word_pattern": _WORD.pattern,
            "long_ngram": LONG_NGRAM,
            "short_ngram": SHORT_NGRAM,
            "long_min_alpha": LONG_MIN_ALPHA,
            "short_min_alpha": SHORT_MIN_ALPHA,
            "span_words": SPAN_WORDS,
            "primary_keys": sorted(PRIMARY_KEYS),
            "owners": self.owners,
            "sizes": self.sizes,
            **metadata,
        }
        (directory / "index.json").write_text(json.dumps(summary, ensure_ascii=False, indent=1), encoding="utf-8")

    @classmethod
    def load(cls, directory) -> "EvalIndex":
        directory = Path(directory)
        summary = json.loads((directory / "index.json").read_text(encoding="utf-8"))
        if summary.get("format") != "ttt_eval_index_v2":
            raise ValueError("评测索引格式不受支持。")
        expected = (LONG_NGRAM, SHORT_NGRAM, SPAN_WORDS)
        if (summary["long_ngram"], summary["short_ngram"], summary["span_words"]) != expected:
            raise ValueError("评测索引的匹配参数与当前代码不一致。")
        arrays = [
            np.load(directory / f"{name}{part}.npy", mmap_mode="r", allow_pickle=False)
            for name in cls.tables
            for part in ("", "_owner")
        ]
        return cls(summary["owners"], *arrays)


class EvalIndexBuilder:
    """逐条加入评测文本，``finish`` 时排序去重成 ``EvalIndex``。"""

    def __init__(self):
        self.owners: list[str] = []
        self._ids: dict[str, int] = {}
        self._rows = {name: [] for name in EvalIndex.tables}
        self._hasher = _WordHasher()

    def _append(self, table: str, owner: str, hashes: np.ndarray) -> int:
        if not hashes.size:
            return 0
        if owner not in self._ids:
            self._ids[owner] = len(self.owners)
            self.owners.append(owner)
        self._rows[table].append((hashes, self._ids[owner]))
        return int(hashes.size)

    def add(self, owner: str, text: str, *, primary: bool = False) -> int:
        """加入一段 benchmark 文本，返回新增的 n-gram 数；``primary`` 表示这是题干字段。"""
        words = self._hasher(text)
        if words.size >= LONG_NGRAM:
            return self._append("ngram13", owner, ngram_hashes(words, LONG_NGRAM, LONG_MIN_ALPHA))
        if primary and words.size >= SHORT_NGRAM:
            return self._append("ngram8", owner, ngram_hashes(words, SHORT_NGRAM, SHORT_MIN_ALPHA))
        return 0

    def add_document(self, owner: str, text: str) -> int:
        """加入一篇 held-out 长文档，按连续逐字重合判定。"""
        return self._append("span13", owner, ngram_hashes(self._hasher(text), LONG_NGRAM, LONG_MIN_ALPHA))

    def finish(self) -> EvalIndex:
        if len(self.owners) > 65535:
            raise ValueError("评测来源数量超过 uint16 能表示的范围。")
        arrays = []
        for table in EvalIndex.tables:
            rows = self._rows[table]
            if rows:
                hashes = np.concatenate([row[0] for row in rows])
                owners = np.concatenate([np.full(row[0].size, row[1], dtype=np.uint16) for row in rows])
                hashes, first = np.unique(hashes, return_index=True)
                owners = owners[first]
            else:
                hashes, owners = np.zeros(0, dtype=np.uint64), np.zeros(0, dtype=np.uint16)
            arrays += [hashes, owners]
        return EvalIndex(self.owners, *arrays)


def iter_strings(value, key: str = ""):
    """递归列出 JSON 值里的全部字符串叶子，连同它所在的字段名。"""
    if isinstance(value, str):
        yield key, value
    elif isinstance(value, dict):
        for name, item in value.items():
            yield from iter_strings(item, str(name))
    elif isinstance(value, (list, tuple)):
        for item in value:
            yield from iter_strings(item, key)


def keep_code_file(item: dict, *, languages=CODE_LANGUAGES, max_chars: int = 100_000) -> bool:
    """Stack v3 文件过滤：宽松许可证、非第三方目录、常见语言，去掉压缩、生成和数据型文件。"""
    if item.get("license_type") != "permissive" or item.get("is_vendor"):
        return False
    if item.get("language") not in languages:
        return False
    content = item.get("content")
    if not isinstance(content, str) or not 64 <= len(content) <= max_chars:
        return False
    lines = content.split("\n")
    if max(map(len, lines)) > 1000 or len(content) / len(lines) > 100:
        return False
    if sum(character.isalnum() for character in content) < 0.25 * len(content):
        return False
    head = "\n".join(lines[:5]).lower()
    return not any(marker in head for marker in _GENERATED_MARKERS)


def _tree_order(path: str):
    """同一目录的文件排在子目录之前，目录按深度优先展开。"""
    parts = path.split("/")
    return tuple((1, part) for part in parts[:-1]) + ((0, parts[-1]),)


def render_repository(row: dict, *, max_chars: int = 400_000, languages=CODE_LANGUAGES) -> str | None:
    """把一个仓库渲染成一篇文档：仓库名，然后是按目录顺序排列的各个文件。

    Stack v3 的一行会把同一个文件重复列出多次，这里按 ``(路径, 内容)`` 去重。超过
    ``max_chars`` 后不再追加文件，避免个别巨型仓库占掉过多训练数据。
    """
    unique = {}
    for item in row.get("files") or ():
        path = item.get("file_path")
        if isinstance(path, str) and path and keep_code_file(item, languages=languages):
            unique.setdefault((path, item.get("content_id")), item)
    if not unique:
        return None
    sections, size = [f"Repository: {row.get('repo_path')}"], 0
    for item in sorted(unique.values(), key=lambda item: _tree_order(item["file_path"])):
        if size and size + len(item["content"]) > max_chars:
            break
        sections.append(f"File: {item['file_path']}\n{item['content']}")
        size += len(item["content"])
    return "\n\n".join(sections)


def render_math_problem(row: dict) -> str | None:
    """NuminaMath 的一行渲染成“题目 + 解答”；只保留题目和解答都被标注为有效的行。"""
    if row.get("problem_is_valid") != "Yes" or row.get("solution_is_valid") != "Yes":
        return None
    problem, solution = row.get("problem"), row.get("solution")
    if not isinstance(problem, str) or not isinstance(solution, str):
        return None
    problem, solution = problem.strip(), solution.strip()
    if not problem or not solution:
        return None
    return f"Problem:\n{problem}\n\nSolution:\n{solution}"
